const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [], remote = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url())) remote.push(r.url()); });
  const url = pathToFileURL(path.resolve(__dirname, '../index.html')).href;
  try {
    await page.goto(url);
    await page.waitForFunction(() => window.MiamiRace?.state.frameCount > 3);
    assert.equal(await page.locator('img,image,canvas').count(), 0);
    assert.equal(await page.locator('.car-node').count(), 10);
    await page.locator('#play-pause').click();
    const frozen = await page.evaluate(() => MiamiRace.state.time);
    await page.waitForTimeout(120);
    assert.equal(await page.evaluate(() => MiamiRace.state.time), frozen);
    await page.locator('#zoom-in').click();
    assert.equal(await page.locator('#zoom-value').textContent(), '125%');
    assert.equal(await page.locator('#camera').getAttribute('transform'), await page.locator('#activity-camera').getAttribute('transform'));
    await page.locator('#reset-camera').click();
    await page.locator('[data-venue="turn5"]').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('#info-title').textContent(), 'TURN 5 LOFTS');
    assert.match(await page.locator('#info-book').getAttribute('href'), /^mailto:.*subject=/);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#venue-info').isVisible(), false);
    await page.locator('[data-car="0"]').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('#tooltip').isVisible(), true);
    await page.mouse.click(450, 800);
    assert.equal(await page.locator('#tooltip').isVisible(), false);
    await page.locator('#venue-map').focus();
    await page.keyboard.press('+');
    assert.equal(await page.locator('#zoom-value').textContent(), '125%');
    await page.keyboard.press('0');
    const sim = await page.evaluate(() => { MiamiRace.advance(170); return MiamiRace.snapshot(); });
    assert.ok(sim.events.overtakes > 0 && sim.events.pitEntries > 1 && sim.events.pitStops > 0 && sim.events.pitExits > 0);
    assert.equal(new Set(sim.cars.map(c => c.position)).size, 10);
    assert.ok(sim.cars.every(c => Number.isFinite(c.x) && Number.isFinite(c.y) && Number.isFinite(c.angle)));
    await page.screenshot({ path: path.resolve(__dirname, '../previews/preview-live-venue.png') });
    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    mobile.on('pageerror', e => errors.push(e.message));
    await mobile.goto(url);
    await mobile.waitForFunction(() => window.MiamiCamera);
    const cdp = await mobile.context().newCDPSession(mobile);
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 145, y: 400 }, { x: 245, y: 400 }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 85, y: 400 }, { x: 305, y: 400 }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    assert.ok(await mobile.evaluate(() => MiamiCamera.view.scale > 1.5));
    await mobile.locator('#reset-camera').tap();
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth), 390);
    await mobile.screenshot({ path: path.resolve(__dirname, '../previews/preview-live-mobile.png') });
    assert.deepEqual(errors, []);
    assert.deepEqual(remote, []);
    console.log('PASS: offline vector scene, race/pit logic, camera, keyboard, details, booking link, tooltips and mobile pinch.', sim.events);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
